// Accounts tab: grouped balances, open an account, edit from a row, Transactions tab shows all.
import { launch } from './lib.mjs'
const { page, errors, shot } = await launch({ outDir: process.env.SCREENSHOT_DIR ?? '/tmp/ft-shots' })
console.log('sidebar lists accounts:', (await page.getByRole('navigation', { name: 'Accounts' }).count()) > 0)
await page.getByRole('tab', { name: 'Accounts' }).click()
console.log('title:', await page.locator('.page-header h2').innerText())
await shot('accounts-page')
console.log('net worth shown', await page.getByText('Net worth').count(), 'time(s) (expect 1: the Accounts page card)')
await page.getByRole('button', { name: 'Add account', exact: true }).click()
await page.getByRole('dialog').getByLabel('Name').fill('Holiday Fund')
await page.getByRole('dialog').getByRole('button', { name: 'Add account' }).click()
await page.getByRole('button', { name: 'Open Holiday Fund' }).waitFor()
console.log('added account from Accounts page')
await page.getByRole('button', { name: 'Edit account Savings' }).click()
const dlg = page.getByRole('dialog')
console.log('dialog title:', await dlg.getByRole('heading').first().innerText())
await shot('accounts-edit')
await dlg.getByLabel('Name').fill('Rainy Day')
await dlg.getByRole('button', { name: /^Save/ }).click()
await page.getByRole('button', { name: 'Open Rainy Day' }).waitFor()
console.log('renamed ok; still on', await page.locator('.page-header h2').innerText())
await page.getByRole('button', { name: 'Open Visa' }).click()
console.log('after open:', await page.locator('.page-header h2').innerText())
await page.getByRole('button', { name: 'Edit account', exact: true }).click()
console.log('header edit dialog:', await page.getByRole('dialog').getByRole('heading').first().innerText())
await page.keyboard.press('Escape')
// Account filter on Transactions
await page.getByRole('button', { name: /^Filters/ }).click()
console.log('filter shows Visa:', await page.getByLabel('Account filter').inputValue(), await page.getByLabel('Account filter').locator('option:checked').innerText())
await page.getByLabel('Account filter').selectOption({ label: 'Chequing' })
await page.waitForTimeout(500)
console.log('title after filter:', await page.locator('.page-header h2').innerText())
await shot('accounts-filter')
await page.getByLabel('Account filter').selectOption({ label: 'All accounts' })
await page.waitForTimeout(500)
console.log('title after all:', await page.locator('.page-header h2').innerText())
console.log('ERRORS', errors)
process.exit(0)
