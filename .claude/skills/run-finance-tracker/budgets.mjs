// Click through the Budgets tab: add a budget, edit it, see spent and the hide-from-budgets marker.
import { launch } from './lib.mjs'

const { app, page, errors, shot } = await launch()
await page.getByRole('tab', { name: 'Budgets', exact: true }).click()
await page.waitForTimeout(400)
const opts = await page.getByLabel('Category to budget').locator('option').allInnerTexts()
console.log('OPTIONS:', opts.slice(0, 4))
await page.getByLabel('Category to budget').selectOption({ index: 1 })
await page.getByLabel('Monthly budget amount').fill('400')
await page.getByRole('button', { name: 'Add budget' }).click()
await page.waitForTimeout(500)
await shot('budgets-added')
console.log('TABLE:', (await page.locator('table').first().innerText()).replace(/\n+/g, ' | '))
const input = page.getByLabel(/^Budget for /).first()
await input.fill('50')
await input.blur()
await page.waitForTimeout(500)
console.log('EDITED:', await page.getByLabel(/^Budget for /).first().inputValue())
await input.fill('0')
await input.blur()
await page.waitForTimeout(500)
console.log('REMOVED:', await page.getByLabel(/^Budget for /).count())
console.log('ERRORS:', errors)
await app.close()
